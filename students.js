const API_URL = "http://127.0.0.1:8000";

let students = [];
let studentFaces = [];


// ==========================================
// LOAD STUDENTS AND FACES
// ==========================================

async function loadStudents() {

    const studentsContainer =
        document.getElementById("studentsContainer");

    try {

        studentsContainer.innerHTML =
            "<p>Loading students and photos...</p>";


        // Fetch students and student faces

        const responses = await Promise.all([

            fetch(`${API_URL}/students`),

            fetch(`${API_URL}/student-faces`)

        ]);


        const studentsResponse = responses[0];

        const facesResponse = responses[1];


        // Check responses

        if (!studentsResponse.ok) {

            throw new Error(
                "Failed to fetch students"
            );

        }


        if (!facesResponse.ok) {

            throw new Error(
                "Failed to fetch student faces"
            );

        }


        // Convert responses to JSON

        const studentsResult =
            await studentsResponse.json();

        const facesResult =
            await facesResponse.json();


        // Check API success

        if (!studentsResult.success) {

            throw new Error(
                studentsResult.error ||
                "Unable to load students"
            );

        }


        if (!facesResult.success) {

            throw new Error(
                facesResult.error ||
                "Unable to load student faces"
            );

        }


        // Store data

        students = studentsResult.data || [];

        studentFaces = facesResult.data || [];


        console.log("Students:", students);

        console.log("Student Faces:", studentFaces);


        // Update total students

        document.getElementById(
            "totalStudents"
        ).textContent = students.length;


        // Display students

        displayStudents(students);

    }

    catch (error) {

        console.error(
            "Students Error:",
            error
        );


        studentsContainer.innerHTML = `

            <p style="color: red;">

                Failed to load students.

                <br><br>

                ${error.message}

            </p>

        `;

    }

}


// ==========================================
// DISPLAY STUDENTS
// ==========================================

function displayStudents(studentList) {

    const studentsContainer =
        document.getElementById(
            "studentsContainer"
        );


    // No students

    if (studentList.length === 0) {

        studentsContainer.innerHTML =
            "<p>No students found.</p>";

        return;

    }


    // Create student cards

    studentsContainer.innerHTML =
        studentList.map(

            function (student, index) {


                // Get all faces belonging to this student

                const faces =
                    studentFaces.filter(

                        function (face) {

                            return String(
                                face.student_id
                            ) === String(
                                student.student_id
                            );

                        }

                    );


                // ==========================================
                // CREATE PHOTOS HTML
                // ==========================================

                let photosHTML = "";


                if (faces.length > 0) {

                    photosHTML =
                        faces.map(

                            function (face) {

                                // IMPORTANT:
                                // Use image_url generated by FastAPI

                                if (!face.image_url) {

                                    return `

                                        <div class="no-faces">

                                            Image unavailable

                                        </div>

                                    `;

                                }


                                return `

                                    <div class="face-image-container">

                                        <img

                                            src="${face.image_url}"

                                            alt="${student.student_name}"

                                            class="student-face-image"

                                            loading="lazy"

                                        >

                                    </div>

                                `;

                            }

                        ).join("");

                }

                else {

                    photosHTML = `

                        <div class="no-faces">

                            <i class="fa-solid fa-image"></i>

                            <span>No photos uploaded</span>

                        </div>

                    `;

                }


                // ==========================================
                // RETURN STUDENT CARD
                // ==========================================

                return `

                    <div class="student-card">


                        <!-- Student Information -->

                        <div class="student-info">


                            <div class="student-number">

                                ${String(
                                    index + 1
                                ).padStart(
                                    2,
                                    "0"
                                )}

                            </div>


                            <div>

                                <div class="student-name">

                                    ${student.student_name || "Unknown"}

                                </div>


                                <div class="student-id">

                                    Student ID:
                                    ${student.student_id || "-"}

                                </div>

                            </div>


                        </div>


                        <!-- Student Photos -->

                        <div class="student-faces-section">


                            <h4>

                                <i class="fa-solid fa-camera"></i>

                                Uploaded Face Photos
                                (${faces.length})

                            </h4>


                            <div class="student-faces">

                                ${photosHTML}

                            </div>


                        </div>


                    </div>

                `;

            }

        ).join("");

}


// ==========================================
// SEARCH STUDENTS
// ==========================================

function searchStudents() {

    const searchInput =
        document.getElementById(
            "searchStudent"
        );


    if (!searchInput) {

        return;

    }


    searchInput.addEventListener(

        "input",

        function () {


            const searchValue =
                this.value
                    .toLowerCase()
                    .trim();


            const filteredStudents =
                students.filter(

                    function (student) {

                        const name =
                            String(
                                student.student_name || ""
                            ).toLowerCase();


                        const id =
                            String(
                                student.student_id || ""
                            ).toLowerCase();


                        return (

                            name.includes(searchValue)

                            ||

                            id.includes(searchValue)

                        );

                    }

                );


            displayStudents(filteredStudents);

        }

    );

}


// ==========================================
// PAGE LOAD
// ==========================================

document.addEventListener(

    "DOMContentLoaded",

    function () {

        searchStudents();

        loadStudents();

    }

);